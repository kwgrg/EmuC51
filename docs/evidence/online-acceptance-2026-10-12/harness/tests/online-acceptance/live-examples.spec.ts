import {test,expect} from '../../online-fixture';
import {readFile,writeFile} from 'node:fs/promises';
for(const mixed of [false,true])test(`现网内置${mixed?'C-SDAS':'单C'}：编辑、编译、加载、断点、单步、运行暂停与截图`,async({page},info)=>{
 await page.goto('/#editor');
 await page.getByRole('button',{name:mixed?'C + SDAS 示例':'单文件 C 示例',exact:true}).click();
 const edit=page.getByLabel('C 编译源码');
 const source=await edit.inputValue();
 await edit.fill(source.replace(mixed?'add_two(5)':'counter = 0;',mixed?'add_two(9)':'counter = 7;')+'\n/* PUBLIC_ACCEPTANCE_20261012_NO_UPLOAD */\n');
 if(mixed){await page.getByLabel('编译源文件',{exact:true}).selectOption('bridge.asm');await edit.fill((await edit.inputValue()).replace('add a,#2','add a,#3'));}
 await page.getByRole('button',{name:'编译 C 工程',exact:true}).click();
 await expect(page.getByTestId('c-build-status')).toContainText('编译成功');
 await page.getByRole('button',{name:'加载 C 编译固件',exact:true}).click();
 await expect(page.getByTestId('sdcc-status')).toContainText('已校验文件摘要');
 const line=mixed?4:6;
 if(mixed)await page.getByLabel('工程源文件',{exact:true}).selectOption('main.c');
 await page.getByRole('button',{name:`切换源码第 ${line} 行断点`,exact:true}).click();
 const run=page.locator('.control-strip').getByRole('button',{name:'运行'});
 await run.click();await expect(page.locator('.footer-status')).toContainText('断点暂停');
 await page.screenshot({path:info.outputPath('breakpoint.png'),fullPage:true});
 await page.getByRole('button',{name:`切换源码第 ${line} 行断点`,exact:true}).click();
 const oldPC=await page.getByTestId('register-PC').innerText();
 await page.getByRole('button',{name:'单步',exact:false}).click();
 await expect(page.getByTestId('register-PC')).not.toHaveText(oldPC);
 await page.getByLabel('最大执行单元').fill('100000000');
 await run.click();await expect(page.locator('.run-state')).toContainText('运行中');
 await page.getByRole('button',{name:'暂停',exact:false}).click();
 await expect(page.locator('.run-state')).toContainText('已暂停');
 await expect(page.locator('.footer-status')).toContainText('执行已暂停');
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'导出工作区',exact:true}).click();
 const workspace=JSON.parse(await readFile((await(await download).path())!,'utf8'));
 if(mixed)expect(workspace.cpu.sfr[0x10]).toBe(12);
 await writeFile(info.outputPath('behavior.json'),JSON.stringify({oldPC,pausedPC:await page.getByTestId('register-PC').innerText(),p1:workspace.cpu.sfr[0x10],instructions:workspace.cpu.instructions,sourceContainsMarker:JSON.stringify(workspace).includes('PUBLIC_ACCEPTANCE_20261012_NO_UPLOAD')},null,2));
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:info.outputPath('desktop-debug.png')});
 const nav=page.getByRole('navigation',{name:'主导航',exact:true});
 await nav.getByRole('button',{name:'SYS_MEM',exact:true}).click();await page.screenshot({path:info.outputPath('desktop-memory.png')});
 await nav.getByRole('button',{name:'I/O_PORTS',exact:true}).click();await page.screenshot({path:info.outputPath('desktop-io.png')});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('navigation',{name:'移动端导航',exact:true}).getByRole('button',{name:'CODE',exact:true}).click();
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:info.outputPath('mobile-debug.png')});
});
