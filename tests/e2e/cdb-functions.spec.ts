import { expect, test } from "@playwright/test";
test("真实 C 函数注释保留机器帧、入口导航与恢复后的未知历史", async ({ page }) => {
  await page.goto("/#editor");
  await page.getByLabel("导入 SDCC 构建文件").setInputFiles(["emuc51-sdcc.json", "frames.c", "frames.ihx", "frames.cdb"].map(name => `tests/fixtures/sdcc-frames/${name}`));
  await expect(page.getByTestId("sdcc-status")).toContainText("已校验文件摘要 · frames.c");
  await page.getByLabel("断点地址").fill("00B0");
  await page.getByRole("button", { name: "添加断点", exact: true }).click();
  await page.locator(".control-strip").getByRole("button", { name: "运行" }).click();
  await expect(page.getByTestId("register-PC")).toContainText("00B0");
  await expect(page.getByTestId("call-frame")).toHaveCount(2);
  await expect(page.getByTestId("frame-function").first()).toContainText("CDB::frames::Fframes$leaf$0$0");
  await expect(page.getByTestId("frame-function").nth(1)).toContainText("CDB::frames::G$nested$0$0");
  for (let i = 0; i < 2; i++) await page.getByRole("button", { name: "查看函数 nested 入口汇编" }).click();
  await expect(page.getByLabel("反汇编起始地址")).toHaveValue("00B3");
  await expect(page.getByTestId("register-PC")).toContainText("00B0");
  await page.goto("/#io"); await page.goto("/#editor");
  await expect(page.getByTestId("frame-function").first()).toContainText("leaf");
  await page.setViewportSize({ width: 375, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "跳出" }).click();
  await expect(page.getByTestId("register-PC")).toContainText("00B6");
  await expect(page.getByTestId("call-frame")).toHaveCount(1);
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "导出工作区", exact: true }).click(); await download;
  await expect(page.getByRole("main")).toHaveAttribute("data-save-state", "saved");
  await page.reload();
  await expect(page.getByTestId("sdcc-status")).toContainText("已校验文件摘要");
  await expect(page.getByTestId("call-stack")).toContainText("快照不含调用历史");
  await expect(page.getByTestId("frame-function")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "跳出" })).toBeDisabled();
  await page.getByTestId("workbench-firmware-input").setInputFiles({ name: "plain.bin", mimeType: "application/octet-stream", buffer: Buffer.from([0x12, 0, 4, 0, 0x22]) });
  await expect(page.getByTestId("firmware-name")).toContainText("plain.bin");
  await page.getByRole("button", { name: "单步" }).click();
  await expect(page.getByTestId("call-frame")).toHaveCount(1);
  await expect(page.getByTestId("frame-function")).toHaveCount(0);
});
